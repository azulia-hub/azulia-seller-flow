    await page.setViewportSize({ width, height:900 })
    await uploadReport(page)
    await navigate(page, 'Returns')
    await page.locator('.global-filter-card').evaluate((element: HTMLDetailsElement) => { element.open = true })
    await page.getByLabel('Calculate by').selectOption('POSTED_ACTIVITY')
    await page.locator('.global-filter-card > summary').click()
    for (const theme of ['light', 'dark']) {
      await page.getByRole('combobox', { name:'Appearance', exact:true }).selectOption(theme)
      const cards = page.locator('.return-kpi')
      await expect(cards.first()).toBeVisible()
      for (const card of await cards.all()) {
        expect(await card.evaluate(element => getComputedStyle(element).backgroundImage)).toBe('none')
      }
      const contrast = await cards.first().evaluate(element => {
        const rgb = (color: string) => (color.match(/[\d.]+/g) ?? []).slice(0,3).map(Number)
        const luminance = (color: string) => rgb(color).map(value => value / 255).map(value => value <= .04045 ? value / 12.92 : ((value + .055) / 1.055) ** 2.4).reduce((sum,value,index) => sum + value * [.2126,.7152,.0722][index],0)
        const background = luminance(getComputedStyle(element).backgroundColor)
        return ['strong','span','small'].map(selector => {
          const foreground = luminance(getComputedStyle(element.querySelector(selector)!).color)
          return (Math.max(background,foreground) + .05) / (Math.min(background,foreground) + .05)
        })
      })
      expect(Math.min(...contrast)).toBeGreaterThanOrEqual(4.5)
      await page.screenshot({ path:`test-results/returns-${theme}-${width}.png`, animations:'disabled' })
    }
    const returnType = page.getByRole('group', { name:'Return type', exact:true })

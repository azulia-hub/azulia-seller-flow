import { expect, test } from '@playwright/test'

for (const width of [375, 1280]) test(`compact campaign and search evidence retains details at ${width}px`, async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.setViewportSize({ width, height: 850 })
  await page.goto('/tests/fixtures/advertisingWorkspaceHarness.html?repairs=1&detail-sort=1')
  const campaignPreview = page.getByRole('region', { name: 'Top campaigns preview' })
  await expect(campaignPreview.getByRole('button', { name: 'Spend, sort ascending' })).toBeVisible()
  await page.getByRole('tab', { name: 'Campaigns', exact: true }).click()
  const campaigns = page.getByRole('table', { name: 'Campaign performance', exact: true })
  await expect(campaigns.getByRole('button', { name: 'Spend, sort ascending' })).toBeVisible()
  const first = campaigns.locator('.adsw-performance-row').first()
  const firstName = await first.locator('.adsw-entity-link').getAttribute('aria-label')
  await expect(first).toContainText('ENABLED')
  expect((await first.boundingBox())!.height).toBeLessThan(width < 700 ? 230 : 145)
  await first.getByRole('button', { name: /More metrics for/ }).click()
  const expanded = page.getByRole('region', { name: `More metrics for ${firstName}`, exact: true })
  await expect(expanded.getByText('CPC', { exact: true })).toBeVisible()
  await expect(expanded.getByText('ROAS', { exact: true })).toBeVisible()
  await expect(expanded.getByText('Conversion rate', { exact: true })).toBeVisible()
  await campaigns.locator('.adsw-performance-row').nth(1).getByRole('button', { name: /More metrics for/ }).click()
  await expect(expanded).toHaveCount(0)
  await expect(campaigns.locator('.adsw-performance-details')).toHaveCount(1)

  await page.getByRole('tab', { name: 'Search terms', exact: true }).click()
  const terms = page.getByRole('table', { name: 'Search term performance', exact: true })
  const term = terms.locator('.adsw-performance-row').first()
  await expect(term.locator('img')).toBeVisible()
  await expect(term.getByText('Negative', { exact: true })).toBeVisible()
  await expect(term.getByText('Negative', { exact: true })).toHaveCSS('background-color', 'rgb(164, 38, 44)')
  for (const column of ['Spend', 'Attributed Sales', 'ACOS', 'Purchases']) {
    const header = terms.getByRole('columnheader').filter({ has: page.getByRole('button', { name: new RegExp(`^${column},`) }) })
    await expect(header).toContainText('↕')
    await header.click({ position: { x: 2, y: 2 } })
    await expect(header).toHaveAttribute('aria-sort', 'ascending')
    await expect(header).toContainText('↑')
    await header.getByRole('button', { name: `${column}, sort descending` }).click()
    await expect(header).toHaveAttribute('aria-sort', 'descending')
    await expect(header).toContainText('↓')
    await header.getByRole('button', { name: `${column}, restore default order` }).click()
    await expect(header).toContainText('↕')
    await expect(header).not.toHaveAttribute('aria-sort')
  }
  expect((await term.boundingBox())!.height).toBeLessThan(width < 700 ? 230 : 145)
  const beforeHeight = (await term.boundingBox())!.height
  await term.getByRole('button', { name: /More metrics for/ }).click()
  const more = page.getByRole('region', { name: 'More metrics for B087654321', exact: true })
  await expect(more.getByText('Campaign negative · ASIN', { exact: true })).toBeVisible()
  await expect(more.getByText('Target & Match', { exact: true })).toBeVisible()
  await expect(more.getByText('Attribution Scope', { exact: true })).toBeVisible()
  await expect(more.getByText('Suggestion only · review before applying in Amazon', { exact: true })).toBeVisible()
  await term.getByRole('button', { name: /Hide metrics for/ }).click()
  await expect(more).toHaveCount(0)
  expect((await term.boundingBox())!.height).toBe(beforeHeight)
  await page.getByText('About search terms & attribution', { exact: true }).click()
  await expect(page.getByText(/spend remains shared at the ad group level/)).toBeVisible()
  await term.locator('.adsw-entity-link').click()
  const drawer = page.getByTestId('entity-detail-drawer')
  await drawer.getByRole('tab', { name: 'Products', exact: true }).click()
  const detailProducts = drawer.getByRole('table', { name: 'Related Products' })
  const firstProduct = detailProducts.locator('tbody tr').first()
  await expect(firstProduct).toContainText('Solid Teak Coffee Table')
  await drawer.getByRole('button', { name: 'Next rows' }).click()
  await expect(firstProduct).toContainText('Detail product 30')
  await detailProducts.getByRole('button', { name: 'Spend, sort ascending' }).click()
  await expect(drawer.getByRole('button', { name: 'Previous rows' })).toBeDisabled()
  await expect(firstProduct.getByRole('button', { name: 'Detail product 1', exact: true })).toBeVisible()
  await detailProducts.getByRole('button', { name: 'Spend, sort descending' }).click()
  await expect(firstProduct).toContainText('Solid Teak Coffee Table')
  await detailProducts.getByRole('button', { name: 'Spend, restore default order' }).click()
  await expect(detailProducts.locator('tbody tr').nth(1).getByRole('button', { name: 'Detail product 1', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect(errors).toEqual([])
  await page.screenshot({ path: `.local/ads-compact-${width}.png`, fullPage: true })
})

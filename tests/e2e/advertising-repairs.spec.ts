import { expect, test } from '@playwright/test'
for (const width of [375, 1280]) test(`long identities, ASIN images and recommendations remain readable at ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: 850 })
  await page.goto('/tests/fixtures/advertisingWorkspaceHarness.html?repairs=1')
  await page.getByRole('tab', { name: 'Products', exact: true }).click()
  await expect(page.locator('.adsw-identity img').first()).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.locator('.adsw-entity-link').first().click()
  const drawer = page.getByTestId('entity-detail-drawer')
  await expect(drawer).toBeVisible()
  await drawer.getByText('Full name', { exact: true }).click()
  expect(await drawer.evaluate(element => element.scrollWidth <= element.clientWidth + 1)).toBe(true)
  await page.keyboard.press('Escape')
  await page.getByRole('tab', { name: 'Search terms', exact: true }).click()
  const row = page.getByRole('row').filter({ hasText: 'B087654321' })
  await expect(row.locator('img')).toBeVisible()
  await expect(row).toContainText('Consider a small bid reduction')
  await expect(row).toContainText('₹9.00')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
